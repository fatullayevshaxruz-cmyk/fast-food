def get_text(key: str, lang: str = "uz", **kwargs) -> str:
    """
    Berilgan kalit (key) va til (lang) bo'yicha matnni qaytaradi.
    kwargs orqali matn ichiga o'zgaruvchilar kiritiladi.
    """
    langs = TRANSLATIONS.get(key, {})
    text = langs.get(lang) or langs.get("uz") or f"[{key}]"
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, ValueError):
            pass
    return text
